def encode(rows):
    assert len(rows) == 8 and all(len(row) == 8 for row in rows)
    data=[]
    for row in rows:
        values=list(map(int,row))
        data.extend([sum((v&1)<<(7-i) for i,v in enumerate(values)),
                     sum(((v>>1)&1)<<(7-i) for i,v in enumerate(values))])
    return data

def array(name, data):
    return 'const uint8_t '+name+'[] = {\n'+ '\n'.join(
        '    '+', '.join(f'0x{v:02x}' for v in data[i:i+16])+','
        for i in range(0,len(data),16))+'\n};\n'

